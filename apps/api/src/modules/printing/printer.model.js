import mongoose from 'mongoose';
import { DEFAULT_LABEL_CONFIG, DEFAULT_RECEIPT_CONFIG, PRINTING } from '@supershop/shared';
import { localized, LocalizedString } from '../i18n/index.js';

const { ObjectId } = mongoose.Schema.Types;
const localizedField = (en = '') => ({
  type: LocalizedString,
  default: () => (en ? { en } : {}),
});

/**
 * A printer the shop has (P6.3): which machine, what it prints, and on what paper. Profiles are
 * DATA — a shop plugs in another till printer and adds a row, nobody deploys anything.
 */
const printerSchema = new mongoose.Schema(
  {
    name: { type: String, required: true },
    /** The printer's name as the operating system (and so QZ Tray) knows it. */
    printer: { type: String, required: true },
    kind: { type: String, enum: PRINTING.KINDS, default: 'receipt' },
    widthMm: { type: Number, enum: [...PRINTING.WIDTHS_MM], default: 80 },
    /** Only this branch's tills use it; null = any branch. */
    branchId: { type: ObjectId, default: null },
    cut: { type: Boolean, default: true },
    openDrawer: { type: Boolean, default: false },
    /** The one a till reaches for when nobody chose: one per kind and branch. */
    isDefault: { type: Boolean, default: false },
    updatedBy: { type: ObjectId, default: null },
  },
  { collection: 'printer_profiles', timestamps: true },
);

printerSchema.index({ kind: 1, branchId: 1 });

export const PrinterProfile =
  mongoose.models.PrinterProfile ?? mongoose.model('PrinterProfile', printerSchema);

/**
 * The shop's receipt layout (P6.4): language (`en` | `ar` | `bilingual`), logo, paper size, which
 * fields appear, header/footer lines, and localized row labels. Source strings are English only;
 * Arabic is generated by the `localized` plugin (§5.7).
 */
const labelKeys = Object.keys(DEFAULT_RECEIPT_CONFIG.labels);
const receiptTemplateSchema = new mongoose.Schema(
  {
    key: { type: String, required: true, unique: true, default: 'default' },
    lang: {
      type: String,
      enum: [...PRINTING.RECEIPT_LANGUAGES],
      default: DEFAULT_RECEIPT_CONFIG.lang,
    },
    widthMm: {
      type: Number,
      enum: [...PRINTING.WIDTHS_MM],
      default: DEFAULT_RECEIPT_CONFIG.widthMm,
    },
    logoMediaId: { type: ObjectId, default: null },
    headerText: localizedField(DEFAULT_RECEIPT_CONFIG.headerText.en),
    footerText: localizedField(DEFAULT_RECEIPT_CONFIG.footerText.en),
    fields: Object.fromEntries(
      Object.entries(DEFAULT_RECEIPT_CONFIG.fields).map(([k, def]) => [
        k,
        { type: Boolean, default: def },
      ]),
    ),
    labels: Object.fromEntries(
      labelKeys.map((k) => [k, localizedField(DEFAULT_RECEIPT_CONFIG.labels[k].en)]),
    ),
    updatedBy: { type: ObjectId, default: null },
  },
  { collection: 'receipt_templates', timestamps: true, minimize: false },
);

receiptTemplateSchema.plugin(localized, {
  fields: ['headerText', 'footerText', ...labelKeys.map((k) => `labels.${k}`)],
});

export const ReceiptTemplate =
  mongoose.models.ReceiptTemplate ?? mongoose.model('ReceiptTemplate', receiptTemplateSchema);

/**
 * The shop's shelf/barcode label template (P6.4): dimensions in mm, barcode height, and which
 * product fields appear above/below the bars.
 */
const labelTemplateSchema = new mongoose.Schema(
  {
    key: { type: String, required: true, unique: true, default: 'default' },
    widthMm: { type: Number, default: DEFAULT_LABEL_CONFIG.widthMm },
    heightMm: { type: Number, default: DEFAULT_LABEL_CONFIG.heightMm },
    barcodeHeight: { type: Number, default: DEFAULT_LABEL_CONFIG.barcodeHeight },
    fields: Object.fromEntries(
      Object.entries(DEFAULT_LABEL_CONFIG.fields).map(([k, def]) => [
        k,
        { type: Boolean, default: def },
      ]),
    ),
    updatedBy: { type: ObjectId, default: null },
  },
  { collection: 'label_templates', timestamps: true, minimize: false },
);

export const LabelTemplate =
  mongoose.models.LabelTemplate ?? mongoose.model('LabelTemplate', labelTemplateSchema);
